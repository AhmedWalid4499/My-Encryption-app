def _as_table(sbox):
    table = np.asarray(sbox, dtype=np.uint8)
    if table.shape != (256,) or len(set(sbox)) != 256:
        raise ValueError("S-box must be a permutation of 0..255")
    return table


def inverse(sbox):
    """Port of CalSboxInv: sboxInv[sbox[i]] = i."""
    table = _as_table(sbox)
    inv = np.empty(256, dtype=np.uint8)
    inv[table] = np.arange(256, dtype=np.uint8)
    return inv


